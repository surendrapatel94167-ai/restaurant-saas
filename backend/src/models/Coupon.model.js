import mongoose from 'mongoose';
import tenantPlugin from '../plugins/mongooseTenantPlugin.js';

const couponSchema = new mongoose.Schema({
  code: { type: String, required: true, uppercase: true, trim: true },
  discountPercentage: { type: Number, required: true, min: 1, max: 90 },
  scope: { type: String, enum: ['all', 'specific'], default: 'all' },
  menuItemIds: [{ type: mongoose.Schema.Types.ObjectId, ref: 'MenuItem' }], // used when scope === 'specific'

  // Empty array = usable by any customer. Non-empty = only these phones can use it
  // (this is how personal/milestone-reward coupons are targeted).
  targetPhones: { type: [String], default: [] },

  isAutoGenerated: { type: Boolean, default: false }, // true for milestone-reward coupons
  isActive: { type: Boolean, default: true },
  expiresAt: Date,

  usedBy: { type: [String], default: [] }, // phones that have redeemed it — each phone can use it once
}, { timestamps: true });

couponSchema.plugin(tenantPlugin);
couponSchema.index({ tenantId: 1, code: 1 }, { unique: true });

export default mongoose.model('Coupon', couponSchema);
